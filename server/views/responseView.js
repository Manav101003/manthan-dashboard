function norm(rows) {
    if (!Array.isArray(rows)) return [];
    return rows.map(row => {
        const o = {};
        for (const k in row) o[colMap[k] || k] = row[k];
        return o;
    });
}

function normOne(row) {
    return row ? norm([row])[0] : {};
}

